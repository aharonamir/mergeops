export function useLocale() {
  return useContext(LocaleContext);
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => (localStorage.getItem("mergeops.locale") as Locale) || "en");

  useEffect(() => {
    localStorage.setItem("mergeops.locale", locale);
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
  }, [locale]);

  return <LocaleContext.Provider value={{ locale, setLocale, t: (key, values) => translate(locale, key, values) }}>{children}</LocaleContext.Provider>;
}

export function translate(locale: Locale, key: TranslationKey, values: TranslationValues = {}) {
  const localeStrings = strings[locale] as Partial<Record<TranslationKey, string>>;
  const template = localeStrings[key] ?? (locale === "zh" ? chineseExtras[key] : undefined) ?? strings.en[key];
  return template.replace(/\{(\w+)\}/g, (_match: string, name: string) => String(values[name] ?? `{${name}}`));
}
